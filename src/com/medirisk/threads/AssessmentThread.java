package com.medirisk.threads;

import com.medirisk.model.Assessment;
import com.medirisk.model.Patient;
import com.medirisk.model.VitalSigns;
import com.medirisk.service.AssessmentService;
import com.medirisk.service.RiskCalculator;

import java.text.SimpleDateFormat;
import java.util.Date;
import java.util.Map;

/**
 * A simple thread implementation to process risk calculations in the background.
 * Demonstrates basic Core Java multi-threading for the academic project.
 */
public class AssessmentThread extends Thread {

    private Patient patient;
    private VitalSigns vitals;
    private RiskCalculator calculator;
    private AssessmentService assessmentService;
    private Assessment resultAssessment;

    public AssessmentThread(Patient patient, VitalSigns vitals,
                            RiskCalculator calculator, AssessmentService assessmentService) {
        this.patient = patient;
        this.vitals = vitals;
        this.calculator = calculator;
        this.assessmentService = assessmentService;
    }

    @Override
    public void run() {
        System.out.println("[Thread: AssessmentWorker] Starting risk calculation for: " + patient.getName());

        try {
            // Optional: Simulate processing delay to demonstrate asynchronous behavior
            Thread.sleep(500); 

            // 1. Calculate risk
            Map<String, Object> riskResult = calculator.calculateRisk(patient.getAge(), vitals);

            // 2. Prepare timestamp
            String date = new SimpleDateFormat("yyyy-MM-dd").format(new Date());
            String time = new SimpleDateFormat("HH:mm:ss").format(new Date());

            // 3. Create Assessment object (ID will be generated by AssessmentService)
            Assessment assessment = new Assessment();
            assessment.setPatientId(patient.getId());
            assessment.setPatientName(patient.getName());
            assessment.setAge(patient.getAge());
            
            assessment.setHeartRate(vitals.getHeartRate());
            assessment.setSystolicBP(vitals.getSystolicBP());
            assessment.setDiastolicBP(vitals.getDiastolicBP());
            assessment.setOxygenLevel(vitals.getOxygenLevel());
            assessment.setTemperature(vitals.getTemperature());
            assessment.setRespiratoryRate(vitals.getRespiratoryRate()); // Added RR
            
            assessment.setRiskScore((Integer) riskResult.get("score"));
            assessment.setRiskLevel((String) riskResult.get("level"));
            assessment.setRecommendation((String) riskResult.get("recommendation"));
            
            assessment.setDate(date);
            assessment.setTime(time);

            // 4. Save via AssessmentService
            resultAssessment = assessmentService.saveAssessment(assessment);

            System.out.println("[Thread: AssessmentWorker] Finished calculation. Score: " 
                + resultAssessment.getRiskScore() + " (" + resultAssessment.getRiskLevel() + ")");

        } catch (InterruptedException e) {
            System.err.println("[Thread: AssessmentWorker] Interrupted: " + e.getMessage());
        } catch (Exception e) {
            System.err.println("[Thread: AssessmentWorker] Error calculating risk: " + e.getMessage());
            e.printStackTrace();
        }
    }

    /**
     * Returns the finalized Assessment object after the thread finishes.
     */
    public Assessment getResultAssessment() {
        return resultAssessment;
    }
}
